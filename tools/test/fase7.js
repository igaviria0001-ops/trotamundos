const { chromium } = require('/opt/npm-tools/node_modules/playwright');
(async () => {
  const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
  const vp = process.argv[2] === 'pc' ? { width: 1440, height: 900 } : { width: 390, height: 844 };
  const p = await (await b.newContext({ viewport: vp, deviceScaleFactor: 2, isMobile: vp.width < 500, hasTouch: true })).newPage();
  const errs = []; p.on('pageerror', e => errs.push(e.message));
  const suf = vp.width < 500 ? '' : '-pc';
  await p.goto('http://localhost:8765/index.html'); await p.waitForTimeout(1000);
  await p.evaluate(() => TMD.UI.ir('expedicion')); await p.waitForTimeout(1200);
  await p.screenshot({ path: `scratch/exp-1${suf}.png` });
  await p.click('.exp-parada >> nth=0'); await p.waitForTimeout(900);
  await p.screenshot({ path: `scratch/exp-2${suf}.png` });
  await p.evaluate(() => TMD.UI.ir('juego_maleta', { cont: 'todo', nivel: '1', rondas: 5 })); await p.waitForTimeout(1600);
  await p.screenshot({ path: `scratch/ml-1${suf}.png` });
  await p.click('.dialogo .btn'); await p.waitForTimeout(300);
  await p.click('.accion .pista'); await p.waitForTimeout(300);
  const c = await p.locator('.globo-cont').boundingBox();
  await p.mouse.click(c.x + c.width / 2, c.y + c.height * .62); await p.waitForTimeout(300);
  await p.screenshot({ path: `scratch/ml-2${suf}.png` });
  await p.click('.accion .aqui'); await p.waitForTimeout(3200);
  await p.screenshot({ path: `scratch/ml-3${suf}.png` });
  await p.click('.hoja .pie .btn'); await p.waitForTimeout(1500);
  await p.screenshot({ path: `scratch/ml-4${suf}.png` });
  console.log('errores', errs);
  await b.close();
})();
